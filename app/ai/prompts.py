# 各類文字的要點數量：系所頁是一頁兩欄，全院總結是一整份簡報
_POINTS = {
    "dept": (
        "strengths（現況／優勢）寫 3 至 4 點：各指標的名次與領先哪些學校，先寫最強的指標。"
        "challenges（挑戰／機會）寫 2 至 3 點：名次在前的學校、正在逼近或已超越本系所的學校、指標之間的落差。"
        "有前期資料時，self_changes（本系所變化）寫 3 至 4 點，附前後期數值或變化率；"
        "rival_changes（競爭學校變化）寫 2 至 3 點，點名成長明顯、超越或逼近本系所的學校。"
    ),
    "college": (
        "strengths（現況／優勢）寫 4 至 5 點：全院表現突出的系所，以及它們在對標學校中領先的指標。"
        "challenges（挑戰／機會）寫 3 至 4 點：哪些系所被對標學校超越或逼近、各系所共同的弱項。"
        "有前期資料時，self_changes（本院變化）寫 3 至 4 點，rival_changes（競爭學校變化）寫 2 至 4 點。"
    ),
}

_DEPT_RULE = "只談這個系所，不評論其他系所；其他單位的數字只用來說明本系所的相對位置。"


def system_prompt(kind: str, tone: str) -> str:
    rules = [*_RULES, _POINTS[kind]]
    if kind == "dept":
        rules.append(_DEPT_RULE)
    body = "\n".join(f"{i}. {r}" for i, r in enumerate(rules, 1))
    return f"{tone.strip()}\n\n請遵守下列規則：\n{body}"
