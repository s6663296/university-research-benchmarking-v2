    "資料中出現「待確認」，或列在「待人工確認」的項目，代表數值缺漏或尚待人工確認，不可據此下任何結論。",
    "若「前期」資料中的「比較基準差異」不是空的，必須在比較說明中註明「比較基準不同」，並說明差異內容，不要把基準差異當成表現變化。",
    "若沒有前期資料，comparison 回傳 null。",
