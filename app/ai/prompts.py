# 各類摘要的要點數量：系所頁只有一頁，全院總結是一整份簡報
_POINTS = {
    "dept": "summary 寫 3 至 4 點：先寫強項，最後一點寫可持續努力的方向；comparison 最多 3 點，挑變化最明顯的指標。",
    "college": "summary 寫 4 至 5 點：全院整體表現、表現突出的系所、可持續努力的方向；comparison 最多 4 點。",
}

_DEPT_RULE = "只談這個系所，不評論其他系所；其他單位的數字只用來說明本系所的相對位置。"


def system_prompt(kind: str, tone: str) -> str:
    rules = [*_RULES, _POINTS[kind]]
    if kind == "dept":
        rules.append(_DEPT_RULE)
    body = "\n".join(f"{i}. {r}" for i, r in enumerate(rules, 1))
    return f"{tone.strip()}\n\n請遵守下列規則：\n{body}"
